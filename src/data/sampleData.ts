export type PresetScenarioId =
  | 'bearing_lubrication_degradation'
  | 'normal_baseline'
  | 'thermal_overload'
  | 'shaft_misalignment'
  | 'nasa_ims_outer_race'
  | 'nasa_cmapss_hpc_degradation';

// Deterministic pseudo-random generator for reproducible engineering curves
function seededNoise(seed: number): number {
  const x = Math.sin(seed * 12.9898 + 78.233) * 43758.5453;
  return (x - Math.floor(x)) * 2 - 1; // -1 to 1
}

export function generateTimeSeriesForScenario(
  scenario: PresetScenarioId,
  ratedRpm = 1500,
  hours = 48
): TimeSeriesPoint[] {
  const points: TimeSeriesPoint[] = [];
  const now = new Date('2026-09-30T10:00:00Z').getTime();

  for (let i = 0; i < hours; i++) {
    const progress = i / (hours - 1); // 0 to 1
    const ts = new Date(now - (hours - 1 - i) * 3600 * 1000).toISOString();
    const n1 = seededNoise(i * 1.1);
    const n2 = seededNoise(i * 2.3);
    const n3 = seededNoise(i * 3.7);

    if (scenario === 'nasa_cmapss_hpc_degradation') {
      // NASA C-MAPSS Turbofan Engine Unit FD001 (Sea Level, HPC Degradation)
      // Progression of severe High-Pressure Compressor (HPC) blade tip erosion up to Cycle 192 (RUL = 14 cycles remaining):
      // T50 Exhaust Gas Temp (temperature) creeps from 642.0°C to 685.4°C (CRITICAL > 680°C trip limit)
      // Ps30 Static Pressure at HPC outlet (pressure) drops from 38.5 bar to 32.4 bar (-15.8% pressure collapse)
      // Core spool Nc (rpm) speeds up from 9050 to 9128 RPM (FADEC tries to sustain thrust)
      // Core casing dynamic vibration (vibration) climbs from 1.85 to 4.25 mm/s (aerodynamic flutter/unbalance)
      // Fuel flow Wf (current) climbs from 28.5 to 34.8 (compensating for dropped core efficiency)
      const degFactor = i < 10 ? 0.04 : Math.pow((i - 6) / (hours - 6), 1.6);
      const load = Number((90.0 + n1 * 0.3).toFixed(1)); // Sea Level Cruise Thrust Demand (90%)
      const rpm = Math.round(9050 + 78 * degFactor + n2 * 4); // Core spool Nc climbs as compressor loses efficiency
      const oilTemp = Number((62.0 + 12.5 * degFactor + n3 * 0.4).toFixed(1)); // 62.0 -> 74.5°C
      const temp = Number((642.0 + 43.4 * degFactor + n1 * 0.6).toFixed(1)); // T50 EGT: 642 -> 685.4°C (CRITICAL)
      const vibration = Number((1.85 + 2.40 * degFactor + n2 * 0.08).toFixed(2)); // 1.85 -> 4.25 mm/s (CRITICAL)
      const pressure = Number((38.5 - 6.1 * degFactor + n3 * 0.05).toFixed(2)); // Ps30: 38.5 -> 32.4 bar (CRITICAL DROP)
      const current = Number((28.5 + 6.3 * degFactor + n1 * 0.3).toFixed(1)); // Fuel flow Wf: 28.5 -> 34.8
      const oilCondition = Number((94.0 - 25.8 * degFactor + n2 * 0.4).toFixed(1)); // 94.0 -> 68.2%

      points.push({
        timestamp: ts,
        hourOffset: i - (hours - 1),
        temperature: temp,
        vibration,
        rpm,
        load,
        pressure,
        current,
        oilTemperature: oilTemp,
        oilCondition,
      });
    } else if (scenario === 'nasa_ims_outer_race') {
      // NASA IMS Set #2: Outer Race Failure on Bearing 1
      // Constant 2000 RPM (AC motor coupled via rub belts), 6000 lbs radial spring load (88%)
      // First 20 hours nominal baseline, then progressive outer raceway spalling on Bearing 1:
      // Bearing 1 DE Temp rises from ~64.5°C to 79.2°C (elevated thermal signature)
      // Vibration RMS rises from 2.10 mm/s to 4.85 mm/s (exceeding baseline, 20 kHz ICP)
      // Force lube pressure drops from 4.0 bar to 3.1 bar, oil temp climbs to 66.8°C
      const degFactor = i < 18 ? 0 : Math.pow((i - 18) / (hours - 18), 1.35);
      const load = Number((88 + n1 * 0.4).toFixed(1)); // Steady 88% (6000 lbs constant spring tension)
      const rpm = Math.round(2000 + n2 * 1.5); // Constant 2000 RPM (±2 RPM stability)
      const oilTemp = Number((58.0 + 8.8 * degFactor + n3 * 0.3).toFixed(1));
      const temp = Number((64.5 + 14.7 * degFactor + n1 * 0.35).toFixed(1)); // Rises to 79.2°C
      const vibration = Number((2.10 + 2.75 * degFactor + n2 * 0.08).toFixed(2)); // Rises to 4.85 mm/s
      const pressure = Number((4.0 - 0.9 * degFactor + n3 * 0.03).toFixed(2)); // Drops to 3.1 bar
      const current = Number((24.2 + 4.2 * degFactor + n1 * 0.4).toFixed(1)); // 24.2 -> 28.4 A
      const oilCondition = Number((92.0 - 17.5 * degFactor + n2 * 0.3).toFixed(1)); // 92 -> 74.5%

      points.push({
        timestamp: ts,
        hourOffset: i - (hours - 1),
        temperature: temp,
        vibration,
        rpm,
        load,
        pressure,
        current,
        oilTemperature: oilTemp,
        oilCondition,
      });
    } else if (scenario === 'normal_baseline') {
      const load = Number((70 + n1 * 2.2).toFixed(1));
      const rpm = Math.round(ratedRpm + n2 * 3);
      const oilTemp = Number((58.5 + (load - 70) * 0.18 + n3 * 0.4).toFixed(1));
      const temp = Number((64.2 + (load - 70) * 0.22 + n1 * 0.5).toFixed(1));
      const vibration = Number((2.35 + n2 * 0.08).toFixed(2));
      const pressure = Number((4.2 + n3 * 0.05).toFixed(2));
      const current = Number((112 + (load - 70) * 1.3 + n1 * 0.8).toFixed(1));
      const oilCondition = Number((91.5 - progress * 0.4).toFixed(1));

      points.push({
        timestamp: ts,
        hourOffset: i - (hours - 1),
        temperature: temp,
        vibration,
        rpm,
        load,
        pressure,
        current,
        oilTemperature: oilTemp,
        oilCondition,
      });
    } else if (scenario === 'bearing_lubrication_degradation') {
      // First 20 hours normal baseline, then load increases slightly and bearing temp + vibration climb ~18% while RPM stays stable
      const degFactor = i < 18 ? 0 : Math.pow((i - 18) / (hours - 18), 1.25);
      const load = Number((71.5 + (i >= 18 ? 6.5 * degFactor : 0) + n1 * 1.2).toFixed(1));
      const rpm = Math.round(ratedRpm + n2 * 2); // Stable RPM!
      const oilTemp = Number((59.0 + 11.4 * degFactor + n3 * 0.35).toFixed(1));
      const temp = Number((64.8 + 13.8 * degFactor + n1 * 0.4).toFixed(1)); // Rises to ~78.6°C
      // Vibration increases ~18.4% from ~2.40 mm/s to ~2.84-3.42 mm/s
      const vibration = Number((2.40 * (1 + 0.184 * degFactor * 1.6) + n2 * 0.05).toFixed(2));
      const pressure = Number((4.15 - 0.42 * degFactor + n3 * 0.04).toFixed(2));
      const current = Number((114 + 12.5 * degFactor + n1 * 0.7).toFixed(1));
      const oilCondition = Number((89.0 - 16.5 * degFactor + n2 * 0.2).toFixed(1));

      points.push({
        timestamp: ts,
        hourOffset: i - (hours - 1),
        temperature: temp,
        vibration,
        rpm,
        load,
        pressure,
        current,
        oilTemperature: oilTemp,
        oilCondition,
      });
    } else if (scenario === 'thermal_overload') {
      const degFactor = i < 12 ? 0 : (i - 12) / (hours - 12);
      const load = Number((74 + 21 * degFactor + n1 * 1.5).toFixed(1));
      const rpm = Math.round(ratedRpm - 15 * degFactor + n2 * 3);
      const oilTemp = Number((61.0 + 23.5 * degFactor + n3 * 0.5).toFixed(1));
      const temp = Number((66.5 + 26.0 * degFactor + n1 * 0.6).toFixed(1));
      const vibration = Number((2.5 + 1.85 * degFactor + n2 * 0.09).toFixed(2));
      const pressure = Number((4.1 - 0.85 * degFactor + n3 * 0.05).toFixed(2));
      const current = Number((118 + 34 * degFactor + n1 * 1.1).toFixed(1));
      const oilCondition = Number((86.0 - 24.0 * degFactor).toFixed(1));

      points.push({
        timestamp: ts,
        hourOffset: i - (hours - 1),
        temperature: temp,
        vibration,
        rpm,
        load,
        pressure,
        current,
        oilTemperature: oilTemp,
        oilCondition,
      });
    } else {
      // shaft_misalignment: high vibration jump without extreme load increase
      const degFactor = i < 15 ? 0 : (i - 15) / (hours - 15);
      const load = Number((72 + n1 * 1.8).toFixed(1));
      const rpm = Math.round(ratedRpm + n2 * 4);
      const oilTemp = Number((60.2 + 4.5 * degFactor + n3 * 0.3).toFixed(1));
      const temp = Number((65.5 + 8.2 * degFactor + n1 * 0.4).toFixed(1));
      const vibration = Number((2.42 + 2.65 * degFactor + n2 * 0.08).toFixed(2));
      const pressure = Number((4.12 + n3 * 0.04).toFixed(2));
      const current = Number((115 + 5.5 * degFactor + n1 * 0.6).toFixed(1));
      const oilCondition = Number((88.0 - 4.0 * degFactor).toFixed(1));

      points.push({
        timestamp: ts,
        hourOffset: i - (hours - 1),
        temperature: temp,
        vibration,
        rpm,
        load,
        pressure,
        current,
        oilTemperature: oilTemp,
        oilCondition,
      });
    }
  }

  return points;
}

